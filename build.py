"""Build the single-file Tracker Desk from this source folder.

    python build.py            -> dist/SGA_Tracker_Desk.html      (readable, one file)
    python build.py --min      -> also dist/SGA_Tracker_Desk.min.html (minified with esbuild)

The single file is what users open (double-click, SharePoint/OneDrive, offline).
index.html in this folder also runs directly for development (no build needed),
but js/13-studio-embed.js is generated here from studio/Swimlane_Studio.html — run build.py after editing the studio.
"""
import json, os, re, subprocess, sys, shutil
ROOT = os.path.dirname(os.path.abspath(__file__))
P = lambda *a: os.path.join(ROOT, *a)
read = lambda p: open(p, encoding="utf-8").read()

# 1. studio -> js/13-studio-embed.js (iframe srcdoc string; "</" escaped so it can sit inside <script>)
studio = read(P("studio", "Swimlane_Studio.html"))
emb = '/* 13-studio-embed.js — GENERATED by build.py from studio/Swimlane_Studio.html, do not edit */\n"use strict";\n' \
      "/* ---- embedded Swimlane Studio (edited in Swimlane_Studio.html, pasted here) ---- */\n" \
      "const STUDIO_HTML=" + json.dumps(studio, ensure_ascii=False).replace("</", "<\\/") + ";\n"
open(P("js", "13-studio-embed.js"), "w", encoding="utf-8").write(emb)

# 2. inline css + js (all scripts become ONE <script>, in index.html order)
index = read(P("index.html"))
css_files = re.findall(r'<link rel="stylesheet" href="(css/[^"]+)">', index)
js_files = re.findall(r'<script src="(js/[^"]+)"></script>', index)
css = "\n".join(read(P(f)) for f in css_files)
js = '"use strict";\n' + "\n".join(re.sub(r'^/\*[^\n]*\*/\n"use strict";\n', "", read(P(f)), count=1) for f in js_files)

def assemble(css, js):
    out = index
    for i, f in enumerate(css_files):
        out = out.replace(f'<link rel="stylesheet" href="{f}">', f"<style>\n{css}</style>" if i == 0 else "", 1)
    first = True
    for f in js_files:
        tag = f'<script src="{f}"></script>'
        out = out.replace(tag + "\n", tag, 1)
        out = out.replace(tag, f"<script>\n{js}</script>\n" if first else "", 1); first = False
    return out

os.makedirs(P("dist"), exist_ok=True)
open(P("dist", "SGA_Tracker_Desk.html"), "w", encoding="utf-8").write(assemble(css, js))
print("dist/SGA_Tracker_Desk.html", os.path.getsize(P("dist", "SGA_Tracker_Desk.html")) // 1024, "KB")
for f in ("Start_Tracker_Desk.cmd", "start-desk.ps1"):   # launcher for SharePoint-link mode (http://localhost)
    if os.path.exists(P("tools", f)): shutil.copy(P("tools", f), P("dist", f))

if "--min" in sys.argv:
    esb = shutil.which("esbuild") or "/opt/npm-tools/node_modules/.bin/esbuild"
    run = lambda src, loader: subprocess.run([esb, "--minify", f"--loader={loader}", "--target=es2020", "--charset=utf8"], input=src.encode(), capture_output=True, check=True).stdout.decode()
    mjs, mcss = run(js, "js"), run(css, "css")
    mjs = mjs.replace("</script", "<\\/script")
    open(P("dist", "SGA_Tracker_Desk.min.html"), "w", encoding="utf-8").write(assemble(mcss, mjs))
    print("dist/SGA_Tracker_Desk.min.html", os.path.getsize(P("dist", "SGA_Tracker_Desk.min.html")) // 1024, "KB")
